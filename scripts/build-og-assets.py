#!/usr/bin/env python3
"""Pre-computes glyph shapes and images for job previews, so the function does almost no work at request time."""
import base64, io, json, re, urllib.request
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
CHARS = [chr(c) for c in range(32, 127)] + list("·–—’‘“”…×•")

def ttf(family, weight):
    css = urllib.request.urlopen(urllib.request.Request(f"https://fonts.googleapis.com/css2?family={family}:wght@{weight}", headers={"User-Agent": "Mozilla/4.0"})).read().decode()
    return urllib.request.urlopen(re.search(r"url\((\S+?\.ttf)\)", css).group(1)).read()

def glyphs(data):
    f = TTFont(io.BytesIO(data)); gs = f.getGlyphSet(); cmap = f.getBestCmap(); upm = f["head"].unitsPerEm
    out = {}
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if not name: continue
        pen = SVGPathPen(gs)
        gs[name].draw(pen)
        out[ch] = [round(gs[name].width), re.sub(r"-?\d+\.\d+", lambda m: str(round(float(m[0]))), pen.getCommands())]
    return {"upm": upm, "g": out}

serif = glyphs(ttf("EB+Garamond", 500))
sans = glyphs(ttf("DM+Sans", 500))
bg = Image.open(ROOT / "public/media/landing/hero.webp").convert("RGB")
w, h = bg.size
bg = bg.crop((0, h - int(w * 630 / 1200), w, h)).resize((1200, 630), Image.LANCZOS).filter(ImageFilter.GaussianBlur(5))
bg = Image.blend(bg, Image.new("RGB", bg.size, (255, 246, 228)), .38)
b1 = io.BytesIO(); bg.save(b1, "JPEG", quality=52)
lg = Image.open(ROOT / "public/logo.webp").convert("RGBA").resize((96, 96), Image.LANCZOS)
b2 = io.BytesIO(); lg.save(b2, "PNG", optimize=True)
(ROOT / "functions/_lib/og-assets.js").write_text(
    "// Generated by scripts/build-og-assets.py. Do not edit.\n"
    f"export const SERIF = {json.dumps(serif, ensure_ascii=False, separators=(',', ':'))};\n"
    f"export const SANS = {json.dumps(sans, ensure_ascii=False, separators=(',', ':'))};\n"
    f"export const BG = 'data:image/jpeg;base64,{base64.b64encode(b1.getvalue()).decode()}';\n"
    f"export const LOGO = 'data:image/png;base64,{base64.b64encode(b2.getvalue()).decode()}';\n"
)
print("assets", (ROOT / "functions/_lib/og-assets.js").stat().st_size)
